#!/usr/bin/env npx tsx
/**
 * division — DeepWiki vs navigation division of labour. Judges wiki-only + nav-only vs the
 * answers-claude gold (combined reuses verdicts.md), buckets each question by which config PASSes,
 * writes logs/reports/division.md. Semantic (judgeAnswers); NOT circular (gold = Claude, not DeepWiki).
 */
import "./utils/load-env.js";
import Anthropic from '@anthropic-ai/sdk';
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import { loadTestcases } from './utils/load-testcases.js';
import { judgeAnswers } from './judge.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const LOGS = path.resolve(__dirname, '..', '..', 'logs');
const OUT = path.join(LOGS, 'reports', 'division.md');

// combined verdicts from verdicts.md's table (| id | verdict | ...). Reuse — never re-judge combined.
function readCombinedVerdicts(): Record<string, string> {
    const p = path.join(LOGS, 'reports', 'verdicts.md');
    const out: Record<string, string> = {};
    if (!fs.existsSync(p)) return out;
    for (const line of fs.readFileSync(p, 'utf-8').split('\n')) {
        const m = line.match(/^\|\s*([\w-]+)\s*\|\s*(PASS|PARTIAL|FAIL)\s*\|/);
        if (m) out[m[1]] = m[2];
    }
    return out;
}

function tally(m: Record<string, string>, ids: string[]): { PASS: number; PARTIAL: number; FAIL: number; judged: number } {
    const t = { PASS: 0, PARTIAL: 0, FAIL: 0, judged: 0 };
    for (const id of ids) { const v = m[id]; if (v === 'PASS' || v === 'PARTIAL' || v === 'FAIL') { (t as any)[v]++; t.judged++; } }
    return t;
}

async function main() {
    const apiKey = process.env.ANTHROPIC_API_KEY || process.env.CLAUDE_API_KEY;
    if (!apiKey) { console.error('ANTHROPIC_API_KEY not set.'); process.exit(1); }
    const client = new Anthropic({ apiKey });
    const { flat: testcases } = loadTestcases(path.join(__dirname, 'utils', 'testcases.json'));
    const ids = testcases.map(tc => tc.id);

    const combined = readCombinedVerdicts();
    if (!Object.keys(combined).length) { console.error('verdicts.md 无 combined 判决 — 先 `npm run judge`'); process.exit(1); }

    console.error('Judging wiki-only + nav-only vs answers-claude gold...');
    const wiki = Object.fromEntries((await judgeAnswers(client, testcases, path.join(LOGS, 'answers-gemini-wiki-only'), '## Gemini Answer')).map(r => [r.id, r.verdict]));
    const nav = Object.fromEntries((await judgeAnswers(client, testcases, path.join(LOGS, 'answers-gemini-nav-only'), '## Gemini Answer')).map(r => [r.id, r.verdict]));

    const PASS = (v?: string) => v === 'PASS';
    const buckets: Record<string, string[]> = { offload: [], moat: [], synergy: [], hard: [], unknown: [] };
    let overlap = 0;
    const matrix: { id: string; w: string; n: string; c: string; bucket: string }[] = [];
    for (const tc of testcases) {
        const w = wiki[tc.id], n = nav[tc.id], c = combined[tc.id];
        if (w === undefined || n === undefined || c === undefined) {
            buckets.unknown.push(tc.id); matrix.push({ id: tc.id, w: w ?? '—', n: n ?? '—', c: c ?? '—', bucket: 'unknown' }); continue;
        }
        if (PASS(w) && PASS(n)) overlap++;
        const bucket = PASS(w) ? 'offload' : PASS(n) ? 'moat' : PASS(c) ? 'synergy' : 'hard';
        buckets[bucket].push(tc.id);
        matrix.push({ id: tc.id, w, n, c, bucket });
    }

    const nz = (a: string[]) => a.length;
    const residual = [...buckets.moat, ...buckets.synergy, ...buckets.hard];
    const tw = tally(wiki, ids), tn = tally(nav, ids), tcb = tally(combined, ids);
    const L: string[] = [];
    L.push(`# division — DeepWiki vs 导航 职责划分(generated by division.ts)\n`);
    L.push(`${new Date().toLocaleString('en-US')} · wiki-only + nav-only 对 answers-claude 金答案判(combined 复用 verdicts.md)。**不循环**(金答案=Claude,非 DeepWiki)。\n`);

    L.push(`## 每配置独立成绩(对 answers-claude 金答案)\n`);
    L.push(`| 配置 | PASS | PARTIAL | FAIL | 判到 |`);
    L.push(`|---|---:|---:|---:|---:|`);
    L.push(`| **wiki-only** | ${tw.PASS} | ${tw.PARTIAL} | ${tw.FAIL} | ${tw.judged} |`);
    L.push(`| **nav-only** | ${tn.PASS} | ${tn.PARTIAL} | ${tn.FAIL} | ${tn.judged} |`);
    L.push(`| **combined** | ${tcb.PASS} | ${tcb.PARTIAL} | ${tcb.FAIL} | ${tcb.judged} |`);
    L.push('');

    L.push(`## 四桶(优先级 offload→moat→synergy→hard,互斥)\n`);
    L.push(`| 桶 | 含义 | 数 | 题 |`);
    L.push(`|---|---|---:|---|`);
    L.push(`| ① offload | wiki-only PASS(该交给 DeepWiki) | ${nz(buckets.offload)} | ${buckets.offload.join(', ') || '—'} |`);
    L.push(`| ② moat | 只有导航拿下(MCP 护城河) | ${nz(buckets.moat)} | ${buckets.moat.join(', ') || '—'} |`);
    L.push(`| ③ synergy | 需合力(单独都不行) | ${nz(buckets.synergy)} | ${buckets.synergy.join(', ') || '—'} |`);
    L.push(`| ④ hard | 谁都拿不下 | ${nz(buckets.hard)} | ${buckets.hard.join(', ') || '—'} |`);
    if (buckets.unknown.length) L.push(`| — unknown | 缺某配置答案/判决 | ${nz(buckets.unknown)} | ${buckets.unknown.join(', ')} |`);
    L.push('');
    L.push(`**DeepWiki 能 offload:** ${nz(buckets.offload)}/${testcases.length}. **导航边际价值(②+③):** ${nz(buckets.moat) + nz(buckets.synergy)}. **overlap(两路都独立 PASS):** ${overlap}.`);
    L.push(`\n> 残差(导航必须扛)= 桶 ②③④ = ${residual.join(', ') || '—'}. 各题 owning-stage 见 metrics.md §3(按 id 交叉)。\n`);

    L.push(`## 三配置逐题 verdict\n`);
    L.push(`| id | wiki-only | nav-only | combined | 桶 |`);
    L.push(`|---|---|---|---|---|`);
    for (const m of matrix) L.push(`| ${m.id} | ${m.w} | ${m.n} | ${m.c} | ${m.bucket} |`);
    L.push('');

    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, L.join('\n'), 'utf-8');
    console.error(`Wrote division.md — wiki-only ${tw.PASS}P · nav-only ${tn.PASS}P · combined ${tcb.PASS}P | buckets offload ${nz(buckets.offload)} · moat ${nz(buckets.moat)} · synergy ${nz(buckets.synergy)} · hard ${nz(buckets.hard)}`);
}

main().catch(e => { console.error('Fatal:', e); process.exit(2); });
